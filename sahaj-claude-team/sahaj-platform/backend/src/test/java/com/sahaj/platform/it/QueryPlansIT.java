    /** Replaces :name by the literal in the map (the production strings have no other colon). */
    private static String bind(String sql, Map<String, String> literals) {
        java.util.regex.Matcher m = java.util.regex.Pattern.compile(":([A-Za-z]+)").matcher(sql);
        StringBuilder out = new StringBuilder();
        while (m.find()) {
            String value = literals.get(m.group(1));
            if (value == null) {
                throw new IllegalStateException("no literal for :" + m.group(1));
            }
            m.appendReplacement(out, java.util.regex.Matcher.quoteReplacement(value));
        }
        m.appendTail(out);
        return out.toString();
    }

