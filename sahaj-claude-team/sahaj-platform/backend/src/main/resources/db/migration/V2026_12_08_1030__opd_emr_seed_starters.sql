-- Starter layout version 1 per department (ADR-020 D4, D6): every section in the department's order with its settings and a
-- copy of its definition and fields. Built from the rows above so the document and the tables cannot differ. valueKind and
-- the lock reason text are not stored: the application derives them (ADR-020 D3). hideLocked = section lock or starter lock.
insert into opd.emr_starter_layout (starter_key, layout_version, layout)
select d.starter_key, d.current_layout_version,
       jsonb_build_object(
         'schemaVersion', 1,
         'sections', (
           select jsonb_agg(
                    jsonb_build_object(
                      'key', p.section_key,
                      'source', 'LIBRARY',
                      'name', s.name,
                      'kind', s.kind,
                      'description', s.description,
                      'part', p.part,
                      'position', p.position,
                      'shown', p.shown,
                      'required', p.required,
                      'print', p.print,
                      'copy', p.copy_from_last,
                      'collapsed', p.collapsed,
                      'whoCanFill', to_jsonb(array_remove(array[
                          case when p.who_doctor then 'DOCTOR' end,
                          case when p.who_nurse then 'NURSE' end,
                          case when p.who_reception then 'RECEPTION' end], null)),
                      'hideLocked', (s.always_shown or p.always_shown),
                      'fields', coalesce((
                        select jsonb_agg(
                                 jsonb_build_object(
                                   'key', f.field_key,
                                   'label', f.label,
                                   'type', f.field_type,
                                   'meta', f.meta,
                                   'required', f.required,
                                   'optionsSource', f.options_source,
                                   'master', f.options_master,
                                   'allowFreeText', f.allow_free_text,
                                   'options', coalesce((
                                     select jsonb_agg(
                                              jsonb_build_object('key', o.option_key, 'label', o.label, 'isNone', o.is_none)
                                              order by o.position)
                                     from opd.emr_section_field_option o
                                     where o.section_key = f.section_key and o.field_key = f.field_key), '[]'::jsonb),
                                   'columns', f.columns,
                                   'min', f.min_value,
                                   'max', f.max_value)
                                 order by f.position)
                        from opd.emr_section_field f
                        where f.section_key = s.section_key), '[]'::jsonb))
                    order by p.position)
           from opd.emr_starter_department_section p
           join opd.emr_section s on s.section_key = p.section_key
           where p.starter_key = d.starter_key))
from opd.emr_starter_department d;
